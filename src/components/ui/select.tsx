function SelectItem({
  className,
  children,
  ...props
}: SelectPrimitive.Item.Props) {
  return (
    // OJO: va `data-[selected]:` con corchetes, NO `data-selected:`, aunque
    // el linter de Tailwind sugiera "canonicalizar" a la forma sin corchetes.
    // En este proyecto `data-selected:` compila a `:where([data-selected=true])`
    // (shape que viene del calendario: react-day-picker sí escribe
    // data-selected="true"), pero Base UI emite el atributo VACÍO
    // —`data-selected=""`, ver getStateAttributesProps— así que ese selector
    // no matchea nunca y el estilo del ítem elegido no se aplica.
    // `data-[selected]:` fuerza `[data-selected]`, que sí matchea por presencia.
    <SelectPrimitive.Item
      data-slot="select-item"
      className={cn(
        "relative flex w-full cursor-default rounded-2xl items-center gap-1.5 py-1.5 pr-8 pl-1.5 text-sm outline-transparent outline border-2 border-transparent transition-colors select-none focus:bg-grisulado-50/25 focus:text-azul-700 focus:outline-2 focus:border-azul-700 data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2 data-[selected]:bg-azul-700 data-[selected]:text-white focus:data-[selected]:bg-azul-700 focus:data-[selected]:text-white my-1",
        className,
      )}
      {...props}
    >
      <SelectPrimitive.ItemText className="flex flex-1 shrink-0 gap-2 whitespace-nowrap">
        {children}
      </SelectPrimitive.ItemText>
      <SelectPrimitive.ItemIndicator
        render={
          <span className="pointer-events-none absolute right-2 flex size-4 items-center justify-center text-white" />
        }
      >
        <CheckIcon className="pointer-events-none" />
      </SelectPrimitive.ItemIndicator>
    </SelectPrimitive.Item>
  );
}

