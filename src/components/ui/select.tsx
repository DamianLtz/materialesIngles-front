import * as React from "react";
import { Select as SelectPrimitive } from "@base-ui/react/select";

import { cn } from "@/lib/utils";
import { ChevronDownIcon, CheckIcon, ChevronUpIcon } from "lucide-react";

const Select = SelectPrimitive.Root;

const obeliscoClassName =
  "h-12 lg:h-11 ring-2 ring-azul-900 enabled:hover:ring-cian-900 data-popup-open:ring-cian-900 data-popup-open:ring-3 enabled:hover:bg-grisulado-50 data-popup-open:bg-grisulado-50 rounded-full";

